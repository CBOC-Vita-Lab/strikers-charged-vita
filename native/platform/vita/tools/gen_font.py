#!/usr/bin/env python3
"""Rasterises DejaVu Sans Mono into the 12x24 1-bit console font used by
vita_console.cpp (vita/src/vita_font.h). Run once; the output is committed so
the build does not need Pillow.   gen_font.py > ../src/vita_font.h
1.3: also the Latin-1 letters U+00A0..U+00FF (Spanish and French texts: accents,
the tilde, inverted marks), and the UTF-8 helpers the screens draw with."""
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 12, 24, 20
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", SIZE)
ascent, descent = font.getmetrics()
top = (H - (ascent + descent)) // 2
print("// Generated by vita/tools/gen_font.py from DejaVu Sans Mono (20 px); do not edit.")
print("// 95 glyphs (ASCII 32..126) and 96 (Latin-1 U+00A0..U+00FF), 12x24 pixels, one uint16_t per row, bit 11 = leftmost pixel.")
print("#pragma once\n#include <cstdint>")
print(f"constexpr int kVitaFontWidth = {W};\nconstexpr int kVitaFontHeight = {H};")
def table(name, codes):
    print(f"constexpr uint16_t {name}[{len(codes)}][24] = {{")
    for code in codes:
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((0, top), chr(code), font=font, fill=255)
        rows = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if img.getpixel((x, y)) >= 110:
                    bits |= 1 << (W - 1 - x)
            rows.append(f"0x{bits:03X}")
        name_ = chr(code) if chr(code) not in "\\" else "backslash"
        print("    {" + ",".join(rows) + "}, // " + (repr(name_) if code < 127 else f"U+{code:04X}"))
    print("};")
table("kVitaFont", range(32, 127))
table("kVitaFontLatin1", range(0xA0, 0x100))
print('''
// The glyph of a code point: ASCII and Latin-1 are drawn, anything else is '?'.
inline const uint16_t* VitaFontGlyph(uint32_t cp) {
    if (cp >= 32 && cp <= 126) return kVitaFont[cp - 32];
    if (cp >= 0xA0 && cp <= 0xFF) return kVitaFontLatin1[cp - 0xA0];
    return kVitaFont['?' - 32];
}
// The next code point of UTF-8 text (advances s). A byte that is not valid UTF-8 is taken as Latin-1, so plain ASCII and older Latin-1 text read as before.
inline uint32_t VitaUtf8Next(const char*& s) {
    const unsigned char c = static_cast<unsigned char>(*s);
    if (c < 0x80) { ++s; return c; }
    const unsigned char d = static_cast<unsigned char>(s[1]);
    if ((c & 0xE0) == 0xC0 && (d & 0xC0) == 0x80) { s += 2; return (uint32_t(c & 0x1F) << 6) | (d & 0x3F); }
    const unsigned char e = d ? static_cast<unsigned char>(s[2]) : 0;
    if ((c & 0xF0) == 0xE0 && (d & 0xC0) == 0x80 && (e & 0xC0) == 0x80) { s += 3; return (uint32_t(c & 0x0F) << 12) | (uint32_t(d & 0x3F) << 6) | (e & 0x3F); }
    const unsigned char f = e ? static_cast<unsigned char>(s[3]) : 0;
    if ((c & 0xF8) == 0xF0 && (d & 0xC0) == 0x80 && (e & 0xC0) == 0x80 && (f & 0xC0) == 0x80) {
        s += 4;
        return (uint32_t(c & 0x07) << 18) | (uint32_t(d & 0x3F) << 12) | (uint32_t(e & 0x3F) << 6) | (f & 0x3F);
    }
    ++s;
    return c;
}
// Characters (code points) of UTF-8 text: what a line is measured in.
inline int VitaUtf8Length(const char* s) {
    int n = 0;
    while (*s) { VitaUtf8Next(s); ++n; }
    return n;
}''')
