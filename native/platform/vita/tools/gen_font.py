#!/usr/bin/env python3
"""Rasterises DejaVu Sans Mono into the 12x24 1-bit console font used by
vita_console.cpp (vita/src/vita_font.h). Run once; the output is committed so
the build does not need Pillow.   gen_font.py > ../src/vita_font.h"""
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 12, 24, 20
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", SIZE)
ascent, descent = font.getmetrics()
top = (H - (ascent + descent)) // 2
print("// Generated by vita/tools/gen_font.py from DejaVu Sans Mono (20 px); do not edit.")
print("// 95 glyphs (ASCII 32..126), 12x24 pixels, one uint16_t per row, bit 11 = leftmost pixel.")
print("#pragma once\n#include <cstdint>")
print(f"constexpr int kVitaFontWidth = {W};\nconstexpr int kVitaFontHeight = {H};")
print("constexpr uint16_t kVitaFont[95][24] = {")
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, top), chr(code), font=font, fill=255)
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                bits |= 1 << (W - 1 - x)
        rows.append(f"0x{bits:03X}")
    name = chr(code) if chr(code) not in "\\" else "backslash"
    print("    {" + ",".join(rows) + "}, // " + repr(name))
print("};")
