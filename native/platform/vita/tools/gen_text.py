#!/usr/bin/env python3
"""Writes platform/sdk/include/np/np_text_table.h (the rows of np_text.h's table) from np_text_strings.tsv. (A .h, not an .inc: the
hardware-test stager rewrites the data paths in .h files, so a text that names ux0:data/mscharged/... stays the same as its English key there.)

    python3 native/platform/vita/tools/gen_text.py           # from the repository root, after editing the .tsv
    python3 native/platform/vita/tools/gen_text.py --check   # exit 1 when the .h is not what the .tsv gives (tests/test_text_table.py)

The .tsv is English<TAB>Spanish<TAB>French, UTF-8, one text per line; '#' lines are comments. The output keeps the UTF-8 bytes as C escapes so
that the compilers never depend on the source character set."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
NP = ROOT / "native/platform/sdk/include/np"
SRC = NP / "np_text_strings.tsv"
OUT = NP / "np_text_table.h"


def rows(path=SRC):
    out = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit(f"{path.name}:{number}: expected 3 tab-separated columns, found {len(parts)}")
        out.append((number, *parts))
    return out


def c_string(text):
    s = []
    for b in text.encode("utf-8"):
        if b == 0x22 or b == 0x5C:
            s.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F and chr(b) != "?":   # ('?' escaped too: no trigraphs)
            s.append(chr(b))
        else:
            s.append(f"\\{b:03o}")
    return '"' + "".join(s) + '"'


def render():
    lines = ["// Generated by native/platform/vita/tools/gen_text.py from np_text_strings.tsv; do not edit. {English, Spanish, French}",
             "// Included inside the table of np_text.h only (no include guard on purpose)."]
    for _, en, es, fr in rows():
        lines.append(f"{{{c_string(en)}, {c_string(es)}, {c_string(fr)}}},")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run native/platform/vita/tools/gen_text.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows())} texts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
