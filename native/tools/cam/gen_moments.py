#!/usr/bin/env python3
"""W5-CAM: nav scripts for the camera pictures: the regression's match (menus of nav_fulltime30: Donkey Kong (home, pad 0) against Waluigi
in the default stadium, 30 fps) followed by play that looks for the brief's moments: build-up in midfield, attacks at the far goal with long
shot charges (the captain's Mega Strike), runs along the far and the near touchline, and the CPU's attacks at our goal (they come by themselves).

    python3 -I tools/cam/gen_moments.py <out.txt> [seed]

The pictures need the same match at every camera level: run it with MSC_TEST_VISIBILITY=all MSC_AI_BUDGET=off (docs/wave5-CAM.md 3).
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PREFIX = os.path.join(HERE, "..", "fps", "nav", "nav_fulltime30.txt")


def prefix_lines():
    out = []
    with open(PREFIX) as f:
        for line in f:
            out.append(line.rstrip("\n"))
            if line.startswith("log STATE open play"):
                break
    return out


def play(rng, cycles):
    out = ["# --- W5-CAM play: the home team attacks +x (screen right) ---"]
    for k in range(cycles):
        side = rng.choice((72, -72))            # far (+y, up the screen) or near touchline
        out.append("log CAM cycle %d" % k)
        out.append("idle %d" % rng.randint(4, 12))
        out.append("hold %d 0 72 %d" % (rng.randint(20, 32), rng.randint(-15, 15)))     # at the ball / with it, toward the far goal
        if rng.random() < 0.5:
            out.append("hold %d 0 %d %d" % (rng.randint(18, 30), rng.randint(20, 45), side))   # out to a touchline
            out.append("hold %d 0 72 %d" % (rng.randint(15, 25), side // 6))                    # along it
        out.append("hold %d 0 72 %d" % (rng.randint(10, 22), rng.randint(-20, 20)))
        if rng.random() < 0.35:
            out.append("hold 3 100 72 0")                                                     # a pass
            out.append("hold %d 0 72 %d" % (rng.randint(8, 16), rng.randint(-25, 25)))
        out.append("hold %d 200 72 %d" % (rng.randint(55, 95), rng.randint(-10, 10)))     # B held: shot charge / Mega Strike
        out.append("idle %d" % rng.randint(10, 30))
        if rng.random() < 0.4:
            out.append("hold %d 800 %d %d" % (rng.randint(3, 6), rng.choice((-72, 72)), rng.randint(-40, 40)))   # a hit / deke
        out.append("hold %d 0 %d %d" % (rng.randint(15, 30), rng.randint(-72, 72), rng.randint(-72, 72)))
    return out


def main(argv):
    out = argv[1]
    seed = int(argv[2]) if len(argv) > 2 else 1
    rng = random.Random(seed)
    lines = ["# Generated by tools/cam/gen_moments.py (seed %d); W5-CAM camera pictures" % seed] + prefix_lines() + play(rng, 60)
    lines += ["log CAM play end", "exit"]
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
