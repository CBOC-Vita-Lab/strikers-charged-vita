#!/usr/bin/env python3
"""gen_a.py <out.inc> <hex-addr>... : generate the translated-function include for dt_a: declarations, wrappers for every callee that is
not extracted (they dispatch to dt_dispatch), the extracted bodies and the address->function table."""
import sys, re, subprocess, pickle
out = sys.argv[1]
addrs = [int(a, 16) for a in sys.argv[2:]]
text = subprocess.run([__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), 'extract.py')] + [('%x' % a) for a in addrs], capture_output=True, text=True).stdout
# strip per-function includes (the shim headers are included once)
text = re.sub(r'#include [<"][^\n]*\n', '', text)
text = re.sub(r'#undef[^\n]*\n', '', text)
text = re.sub(r'#line \d+ "[^"]*"\n', '', text)
callees = set(int(x, 16) for x in re.findall(r'func_([0-9A-Fa-f]{8})\(', text)) | set(int(x, 16) for x in re.findall(r'MKW_STATIC_TRANSLATED_CALL\(0x([0-9A-Fa-f]{8})u', text))
defined = set(addrs)
with open(out, 'w') as f:
    f.write('// GENERATED by gen_a.py\n')
    f.write('#define MKW_STATIC_TRANSLATED_CALL(Target, Entry, Context) do { ApplyRuntimeCallOptions(Target, Context); Entry(Context); } while (false)\n')
    f.write('#include "abi_bridge.h"\n')
    for sf in sorted(set(re.findall(r'func_[0-9A-Fa-f]{8}_statefree', text))):
        f.write('template <class... A> inline void %s(A&&...) { abort(); }\n' % sf)
    for a in sorted(callees | defined):
        f.write('extern "C" void func_%08X(CpuContext*);\n' % a)
    for a in sorted(callees - defined):
        f.write('extern "C" void func_%08X(CpuContext* c) { dt_dispatch(0x%08Xu, c); }\n' % (a, a))
    f.write(text + '\n')
    f.write('static const struct { uint32_t a; void (*f)(CpuContext*); } g_translated[] = {\n')
    for a in sorted(defined): f.write('  { 0x%08Xu, func_%08X },\n' % (a, a))
    f.write('};\n')
print('callees not extracted:', ' '.join('%08x' % a for a in sorted(callees - defined)))
