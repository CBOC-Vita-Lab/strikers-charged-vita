#!/usr/bin/env python3
"""W5 CTL: rasterises DejaVu Sans Condensed Bold (Bitstream Vera / DejaVu licence: free to use, modify and embed) into the anti-aliased
fonts of the Vita-button pictures (platform/sdk/input/np_ctl_font.h): 4-bit coverage, proportional advance, ASCII 32..126.
Run once; the output is committed so the build does not need Pillow.   tools/ctl/gen_ctl_font.py > platform/sdk/input/np_ctl_font.h"""
from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf"
SIZES = [("Small", 17), ("Big", 46)]
print("// Generated by tools/ctl/gen_ctl_font.py from DejaVu Sans Condensed Bold; do not edit.")
print("// Font: DejaVu Sans Condensed Bold. Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is a trademark of")
print("// Bitstream, Inc. DejaVu changes are in the public domain. Rendered glyph data under the Bitstream Vera Fonts licence (it permits")
print("// copying, modifying and distributing the font software with this notice; see fonts-dejavu-core's copyright file).")
print("// Glyphs ASCII 32..126: 4-bit coverage, two pixels per byte (high nibble first), rows of (width + 1) / 2 bytes.")
print("#pragma once\n#include <stdint.h>\nstruct NpCtlGlyph { uint32_t offset; uint8_t width, advance; };")
for name, size in SIZES:
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    H = ascent + descent
    data = []
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch)
        w = max(bbox[2], adv, 1)
        img = Image.new("L", (w, H), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        off = len(data)
        for y in range(H):
            row = [img.getpixel((x, y)) >> 4 for x in range(w)]
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] << 4 | row[i + 1])
        glyphs.append((off, w, adv))
    print(f"constexpr int kNpCtlFont{name}Height = {H};")
    print(f"constexpr int kNpCtlFont{name}Ascent = {ascent};")
    print(f"constexpr NpCtlGlyph kNpCtlFont{name}Glyphs[95] = {{")
    print("    " + ", ".join("{%d, %d, %d}" % g for g in glyphs))
    print("};")
    print(f"constexpr uint8_t kNpCtlFont{name}Data[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        print("    " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    print("};")
