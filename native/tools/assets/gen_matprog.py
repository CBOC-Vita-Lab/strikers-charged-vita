#!/usr/bin/env python3
"""Generate np_matprog.inc: per material program (hash) the parameter block size and texture binding offsets.
Source of truth: the decomp's src/NL/glx/GX*MaterialProgram.cpp (programHash, parameterDataSize, Parameters[]).
Metadata low byte 0x03 = glTextureBinding (u32 texture, u16 index, u8 flags, u8 pad)."""
import re,sys,glob,os
src=sys.argv[1]; out=sys.argv[2]
inc=os.path.join(os.path.dirname(os.path.dirname(src.rstrip('/'))),'..','include','NL','glx') if len(sys.argv)<4 else sys.argv[3]
progs={}
for f in sorted(glob.glob(os.path.join(src,'GX*MaterialProgram.cpp'))):
    t=open(f).read()
    m=re.search(r'programHash\s*=\s*(0x[0-9A-Fa-f]+)',t)
    d=re.search(r'parameterDataSize\s*=\s*(\d+)',t)
    if not d:
        sz=re.search(r'parameterDataSize\s*=\s*sizeof\((\w+)\)',t)
        if sz:
            hdr=os.path.join(inc,os.path.basename(f)[:-4]+'.h')
            ht=open(hdr).read()
            st=re.search(r'struct\s+'+sz.group(1)+r'\s*\{.*?\};\s*//\s*size:\s*(0x[0-9A-Fa-f]+)',ht,re.S)
            if not st: raise SystemExit('cannot size '+sz.group(1)+' in '+hdr)
            class D: 
                def __init__(s,v): s.v=v
                def group(s,i): return str(s.v)
            d=D(int(st.group(1),16))
    c=re.search(r'parameterCount\s*=\s*(\d+)',t)
    if not (m and d and c): 
        continue
    tb=re.search(r'GXMaterialParameter\s+\w+::Parameters\[(\d+)\]\s*=\s*\{(.*?)\n\};',t,re.S)
    ents=[]
    if tb:
        for e in re.finditer(r'\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(\d+)\s*\}',tb.group(2)):
            ents.append((int(e.group(1),16),int(e.group(2),16),int(e.group(3))))
    h=int(m.group(1),16)
    if not d:
        pass
    h=int(m.group(1),16)
    progs[h]=(os.path.basename(f)[:-4],int(d.group(1)),int(c.group(1)),ents)
lines=['/* GENERATED by tools/assets/gen_matprog.py from the decomp (src/NL/glx/GX*MaterialProgram.cpp). Do not edit. */',
       '/* {program hash, parameter block bytes, number of parameters, texture binding offsets (-1 terminated), name} */']
for h,(name,size,cnt,ents) in sorted(progs.items()):
    tex=[o for (_,md,o) in ents if (md&0xFF)==3]
    assert len(ents)==cnt,(name,len(ents),cnt)
    # sanity: every parameter fits the block
    lines.append('{ 0x%08Xu, %d, %d, { %s -1 }, "%s" },'%(h,size,cnt,''.join('%d, '%o for o in tex),name))
open(out,'w').write('\n'.join(lines)+'\n')
print(len(progs),'programs')
