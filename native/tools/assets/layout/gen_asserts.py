#!/usr/bin/env python3
"""gen_asserts.py - emit platform/assets/np_layout_asserts.cpp.

The converters swap the decomp's structs IN PLACE using tables derived from clang -m32 record layouts
(np_layout_*.inc) and a few hard-coded record sizes. This file turns the sizes of every struct whose
header is really included by the probes into static_asserts, so that compiling it for host32, armhf and
Vita (any ABI where long long / double alignment or padding differs) fails loudly instead of
mis-converting data.

  gen_asserts.py <out.cpp> <probe.cpp>:<layout.inc> [...]
"""
import re
import sys

out = sys.argv[1]
includes = []
asserts = []
for spec in sys.argv[2:]:
    probe, inc = spec.split(':')
    for line in open(probe):
        line = line.strip()
        if line.startswith('#include') and line not in includes:
            includes.append(line)
    for m in re.finditer(r'\{ "(\w+)", (\d+), fld_', open(inc).read()):
        asserts.append((m.group(1), int(m.group(2))))
seen = set()
with open(out, 'w') as f:
    f.write('/* GENERATED by tools/assets/layout/gen_asserts.py from the np_layout_*.inc tables. Do not edit.\n')
    f.write(' * The asset converters (platform/assets) swap these structs in place and rely on the sizes below\n')
    f.write(' * (the Wii/MWCC ILP32 layout). Compile this file for every target; a failure means the target ABI lays\n')
    f.write(' * the struct out differently from the Wii and the converter table for it is wrong there. */\n')
    f.write('#include <stddef.h>\n')
    for i in includes:
        f.write(i + '\n')
    f.write('\n#define NPA_SIZE(T, N) static_assert(sizeof(T) == (N), #T ": size differs from the Wii layout the NPA converters assume")\n\n')
    for name, size in asserts:
        if name in seen:
            continue
        seen.add(name)
        f.write('NPA_SIZE(%s, %d);\n' % (name, size))
print('%d asserts -> %s' % (len(seen), out))
