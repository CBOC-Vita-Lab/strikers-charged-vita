#!/usr/bin/env python3
"""The route of the pack proof (docs/BUILDING.md, Making The Shader Seed, step 6): the kit's tour (menus, Domination walk, walk-out, play, a goal with its
celebration and replay), then the pause menu's way out to the main menu and a short match in each stadium named, all in ONE boot, so that the C heap and the program
tables carry over from match to match as they do for a player.

  gen_proof_route.py [--secs 30] [--stadiums 8,7,14,1,3] [--short] <out.txt>

--short: no tour, the main menu and then the stadiums. In the emulator use it for the stadiums and play the tour as a run of its own: the game keeps to the clock at a few
pictures a second, so the tour's match is over before the pause menu can leave it, and a stadium needs --secs 20 or so for the same reason.

Stadium numbers as MSC_STADIUM_HEAVY. Default: Pipeline Central, Lava Pit, Wastelands, Bowser Stadium, Crystal Canyon.
"""
import argparse, os, random

HERE = os.path.dirname(os.path.abspath(__file__))
TOUR = os.path.join(HERE, '../../../tools/console-1.2/routes/tour.txt')

QUIT = """# pause menu, item 6: leave the match; A at the question, A at the next one, back to the main menu
log STATE leaving the match
try wait gs == 5 1800
mash 1000 40 ovl == 80 1200
idle 90
""" + "press 4\nidle 25\n" * 6 + """press 100
idle 60
press 100
idle 120
mash 100 40 scene == 1 2400
wait nbuttons >= 8
idle 60
"""


def play(seed, frames):
    """Held sticks and the odd button, frames in all (the shape of gen_scripts.py monkey)."""
    r = random.Random(seed)
    out, n = [], 0
    while n < frames:
        f = r.choice((8, 14, 20, 30))
        out.append('hold %d %s %d %d' % (f, r.choice(('0', '0', '100', '200', '400', '800')), r.randint(-72, 72), r.randint(-72, 72)))
        n += f
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--secs', type=int, default=30)
    ap.add_argument('--stadiums', default='8,7,14,1,3')
    ap.add_argument('--short', action='store_true')
    ap.add_argument('out')
    a = ap.parse_args()
    tour = open(TOUR).read().split('\n')
    while tour and tour[-1].strip() in ('', 'exit'):
        tour.pop()
    if a.short:
        tour = tour[:tour.index('log STATE main menu, pointer on Domination Mode') + 1] + ['idle 60']
    lines = ['# generated by native/tools/seed/gen_proof_route.py'] + tour
    for i, s in enumerate(int(x) for x in a.stadiums.split(',')):
        if i or not a.short:
            lines += QUIT.rstrip().split('\n')
        lines += ['log @begin stadium-%d' % s,
                  'launch mode=friendly stadium=%d home=3 away=6 hsk=0,1,2 ask=5,6,7 human=0 time=180 skill=0' % s,
                  'wait ingame == 1 4000', 'try wait gs == 1 4000', 'try wait gs == 5 1200', 'log STATE open play in stadium %d' % s]
        lines += play(1000 + s, a.secs * 30)
        lines += ['log @end stadium-%d' % s]
    lines += ['log STATE route done', 'exit', '']
    open(a.out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
