def _stick_moves(seed, frames):
    """Held sticks and the odd pause: frames in all, the same moves for the same seed (gen_proof_route.py's shape, without its random module so the text never changes)."""
    out, n, k = [], 0, seed
    while n < frames:
        k = (k * 1103515245 + 12345) & 0x7FFFFFFF
        f = (8, 14, 20, 30)[(k >> 8) % 4]
        k = (k * 1103515245 + 12345) & 0x7FFFFFFF
        pause = (0, 0, 100, 200, 400, 800)[(k >> 8) % 6]
        k = (k * 1103515245 + 12345) & 0x7FFFFFFF
        x = (k >> 8) % 145 - 72
        k = (k * 1103515245 + 12345) & 0x7FFFFFFF
        y = (k >> 8) % 145 - 72
        out.append("hold %d %d %d %d" % (f, pause, x, y))
        n += f
    return out


def _match(tag, stadium, frames, seconds=180, skill=0):
    return ["log @begin %s" % tag,
            "launch mode=friendly stadium=%d home=3 away=6 hsk=0,1,2 ask=5,6,7 human=0 time=%d skill=%d" % (stadium, seconds, skill),
            "wait ingame == 1 4000", "try wait gs == 1 4000", "try wait gs == 5 1200", "log STATE open play in stadium %d" % stadium] + _stick_moves(1000 + stadium, frames) + ["log @end %s" % tag]


def _stability(stadiums, frames, title, what):
    boot, menus, holds = split_source(source_lines())
    out = HEADER.format(title=title, what=what).splitlines()
    out += body_without_comment_header(boot)
    out += ["log @begin menu-main", "idle 330", "log @end menu-main", "log STATE main menu, pointer on Domination Mode", "idle 60"]
    for i, s in enumerate(stadiums):
        if i:
            out += QUIT.rstrip().split("\n")
        out += _match("stab-%02d-s%d" % (i + 1, s), s, frames)
    out += ["log STATE route done", "exit"]
    return "\n".join(out) + "\n"


