def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when routes/ differs from the generated text")
    args = ap.parse_args()
    OUT.mkdir(exist_ok=True)
    bad = 0
    for name, make in FILES.items():
        text = make()
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                print("DIFFERS: " + name)
                bad = 1
        else:
            path.write_text(text)
            print("wrote %s (%d lines)" % (path.relative_to(REPO), text.count("\n")))
    return bad


if __name__ == "__main__":
    sys.exit(main())
