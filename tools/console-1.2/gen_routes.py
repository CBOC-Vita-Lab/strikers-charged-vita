HEADER = """# {title}
# Generated by tools/console-1.2/gen_routes.py from native/platform/vita/session/nav/match60.txt; edit the generator, not this file.
# {what}
# "@begin <scene>" / "@end <scene>" log lines mark the scenes the analysis reports (README.md, "Scene marks").
"""


def source_lines():
    lines = SOURCE.read_text().splitlines()
    return lines


def split_source(lines):
    """(menu walk up to and including 'wait scene == 5', the stick moves)"""
    def find(prefix, start=0):
        for i in range(start, len(lines)):
            if lines[i].startswith(prefix):
                return i
        raise SystemExit("match60.txt has changed shape: no line starts with %r" % prefix)
    boot_end = find("log STATE main menu")
    stadium = find("wait scene == 5")
    stop = find("stopwhen clock")
    holds = [l for l in lines[stop + 1:] if l.startswith("hold ")]
    return lines[:boot_end], lines[boot_end:stadium + 1], holds


def body_without_comment_header(lines):
    # the first line of match60.txt says "Generated by ..."; the kit's own header replaces it
    return [l for l in lines if not l.startswith("# Generated by")]


def guarded_blocks(holds, clock):
    out = []
    for i in range(0, len(holds), HOLD_BLOCK):
        out.append("if clock < %d" % clock)
        out.extend(holds[i:i + HOLD_BLOCK])
        out.append("endif")
    return out


def tour(menu_dwell=MENU_DWELL, stadium_dwell=STADIUM_DWELL, play_clock=PLAY_CLOCK, title=None):
    boot, menus, holds = split_source(source_lines())
    out = HEADER.format(title=title or "console-1.2 tour: menus, stadium select, walk-out, 60 s of play, a goal sequence with celebration and replay",
                        what="One launch covers every scene class the A/B matrix reports. Same route for every run of the matrix.").splitlines()
    out += body_without_comment_header(boot)
    out += ["# main menu: pointer on Domination Mode, the 105,000-triangle 3D background and glow chain",
            "log @begin menu-main", "idle %d" % menu_dwell, "log @end menu-main"]
    # menus[0] is the 'log STATE main menu' line; the walk to the stadium select follows
    out += menus
    out += ["# stadium select: the pointer starts on PLAY; the stadium preview runs while the script waits",
            "wait onoff == 0x110",
            "log @begin stadium-select", "idle %d" % stadium_dwell, "log @end stadium-select",
            "idle 30", "press 100",
            "log stadium confirmed, loading the match",
            "wait ingame == 1",
            "# the walk-out (cut-scene, depth of field) plays out; no button skips it",
            "log @begin walkout", "try wait gs == 1 4000", "log @end walkout",
            "log STATE kick-off", "try wait gs == 5 1200", "log STATE open play",
            "# %d s of open play: stick moves of nav_match60 in blocks, each block only while the match clock is under %d" % (play_clock, play_clock),
            "log @begin play"]
    out += guarded_blocks(holds, play_clock)
    out += ["log @end play",
            "# a goal sequence (celebration, replay): the CPU team often scores during the %d s; if nobody has" % play_clock + ", run at the goal and shoot, up to",
            "# three tries (Modern layout: Circle shoots). A cut-scene in open play counts as a goal sequence whoever scored.",
            "log @begin goal-run"]
    for _ in range(3):
        out += ["if score0 == 0 && score1 == 0", "vchase 240 none ball", "vchase 150 none goal", "vhold 60 circle", "vpress circle 3 0", "idle 90", "endif"]
    out += ["log @end goal-run",
            "# a goal that has just happened plays out to the next kick-off; if none did, the run still ends",
            "try wait gs == 2 120",
            "if gs == 2", "log @begin goal-sequence", "try wait gs == 1 3600", "log @end goal-sequence", "endif",
            "idle 120", "log tour done", "exit"]
    return "\n".join(out) + "\n"


