# (300 frame intervals: 10 s at 30 fps, 5 s at 60; the median and p95 of 300 samples). A record starts at a change of scene identity, so a dwell of
# CORE_DWELL frames after the change holds one whole record and a little slack.
CORE_DWELL = 330       # frames on the main menu and on the stadium select
CORE_PLAY_CLOCK = 30   # seconds of match clock in the core tour: three records at 30 fps, six at 60
CORE_STADIUM_CLOCK = 20   # seconds of match clock on Pipeline Central and Lava Pit: two records at 30 fps
