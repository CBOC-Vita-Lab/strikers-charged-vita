def replay(frames=REPLAY_FRAMES, title=None):
    """Open play with the moves of nav_match60, over and over, for REPLAY_FRAMES: at each goal (the CPU team's Mega Strikes score most of them) the celebration and the replay play out.
    Two earlier versions ran in Vita3K and scored nothing in 8 minutes of match, so they marked no replay. Run at the goal and shoot: the keeper stopped every shot. Pad left alone: the
    human side's keeper holds the ball until a button is pressed, for ever. A third with skill=0 had no goal in 9 minutes of match either, hence skill=3. Chunks are short because a press inside a replay could skip it, and each ends by waiting for open play."""
    boot, menus, holds = split_source(source_lines())
    out = HEADER.format(title=title or "console-1.2 replay: a match of goals, each with its celebration and replay",
                        what="The switches of replays and cut-scenes have too little to act on in the tour's one goal. A cut-scene or replay is pooled over the run, marked rep-sequence.").splitlines()
    out += body_without_comment_header(boot)
    out += ["log STATE main menu", "idle 60",
            "launch mode=friendly stadium=%d home=3 away=6 hsk=0,1,2 ask=5,6,7 human=0 time=600 skill=3" % VICE,
            "wait ingame == 1 4000",
            "try wait gs == 1 4000", "log STATE kick-off", "try wait gs == 5 1200", "log STATE open play"]
    at = 0
    played = 0
    while played < frames:
        chunk = [holds[(at + k) % len(holds)] for k in range(REPLAY_CHUNK)]
        at += REPLAY_CHUNK
        played += sum(int(l.split()[1]) for l in chunk if l.startswith("hold "))
        out += ["if gs == 5"] + chunk + ["endif",
                "if gs == 2", "log @begin rep-sequence", "try wait gs == 1 3600", "log @end rep-sequence", "endif",
                "try wait gs == 5 || gs == 2 1200"]
    out += ["idle 60", "log replay route done", "exit"]
    return "\n".join(out) + "\n"


