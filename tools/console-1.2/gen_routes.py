def stadium(id_, title, clock=PIPE_CLOCK, nholds=PIPE_HOLDS, mark="pipe", extra="", what=None):
    """Title to a match in one stadium: walk-out and open play, marked pipe-* (the analysis reports them apart from the tour's); lava-* for the core's Lava Pit."""
    boot, menus, holds = split_source(source_lines())
    out = HEADER.format(title=title, what=what or "Launched like the look route, so that only the stadium differs from it. Same match in every run of the route.").splitlines()
    out += body_without_comment_header(boot)
    out += ["log STATE main menu", "idle 60",
            "launch mode=friendly stadium=%d home=3 away=6 hsk=0,1,2 ask=5,6,7 human=0 time=180 skill=0%s" % (id_, extra),
            "wait ingame == 1 4000",
            "log @begin %s-walkout" % mark, "try wait gs == 1 4000", "log @end %s-walkout" % mark,
            "log STATE kick-off", "try wait gs == 5 1200", "log STATE open play",
            "log @begin %s-play" % mark]
    out += guarded_blocks(holds[:nholds], clock)
    out += ["log @end %s-play" % mark, "log stadium route done", "exit"]
    return "\n".join(out) + "\n"


