#!/usr/bin/env python3
"""Generate the console-1.2 route scripts from the repository's own navigation script.

    python3 tools/console-1.2/gen_routes.py            # rewrite routes/*.txt
    python3 tools/console-1.2/gen_routes.py --check    # fail when routes/*.txt differ from what this would write

The menu walk and the list of stick moves come from native/platform/vita/session/nav/match60.txt (the maintained 62-second route,
which also accepts the "create save data" pop-up of a fresh private data folder). What the kit adds are the "@begin <scene>" /
"@end <scene>" log marks the analysis keys on (see README.md, "Scene marks"), the dwell times that give 10-second steady windows,
the walk-out left to play, and a goal sequence (celebration and replay) whoever scores it.

Dwell lengths are presented frames, not seconds: 600 frames are 10 s at 60 fps and 20 s at 30 fps, so every dwell holds at least
one full 10-second window at either rate.
"""
