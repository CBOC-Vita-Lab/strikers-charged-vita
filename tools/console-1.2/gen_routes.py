# dropped, analyse.py --night) and at least two live records even at 20 pictures a second; and the stability routes, which measure nothing.
NIGHT_PLAY_CLOCK = 45      # seconds of match clock in ntour (4-5 records at 30 fps, 9 at 60)
NIGHT_STADIUM_CLOCK = 40   # npipe, nlava: 800 frames at 20 pictures a second = 2 warm-up records and one live one; 2,400 at 60
NIGHT_STADIUM_HOLDS = 110  # stick moves at most (about 2,000 frames)
# w6/crash2.md: twelve matches in ONE boot, across stadiums, the C heap carrying over from match to match as it does for a player (Crystal Canyon 3, Bowser 1,
# Pipeline Central 8, Sand Tomb 15, Wastelands 14, Lava Pit 7, Storm Ship 9, Thunder Island 11, then the first four again). The pause menu's way out between matches is
# native/tools/seed/gen_proof_route.py's, which the pack proof has run on 1.1 and 1.3.
