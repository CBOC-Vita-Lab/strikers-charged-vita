"""The online runs (unit ON of r17-sitting-extra.txt): route scripts for ONE console against the real online service, their STATE lines and their pass rules.

    python3 tools/console-1.2/gen_online.py            # print the runs and their STATE lines
Imported by gen_routes.py (the route files routes/on-*.txt), matrix.py (the runs) and online_check.py (the pass rules). The route text is written here, not by hand.

The routes drive the game's own menus by pad presses exactly as native/tools/mp/lan/online_menu_*.txt do on the host (MULTIPLAYER -> ONLINE -> the choice popup -> Online Central), log a
`STATE ...` line at each screen, and end with `exit` (the console log then has `script exit`). Nothing is typed: the public name comes from MSC_ONLINE_NAME in the run's np-player.txt
(np_online_name.cpp / np_menu_flow.cpp: an environment name wins on every build, so the system keyboard never opens). One console only: no opponent ever appears, so the queue runs cancel.

Scene ids (BaseGameSceneManager.h): 1 main menu, 10 popup, 24 network start, 40 Online Central hub, 41 ranked (player count), 46 rankings, 47 friends list, 49 matchmaking draft, 51 login.
Hub buttons (onctx): 0 FRIEND MATCH, 1 RANKED MATCH, 2 RANKINGS, 3 FRIENDS. The online choice popup (onctx): HOST A ROOM / JOIN WITH A CODE / RANKED MATCH, or with MSC_ONLINE_FRIENDS=1
FRIENDS / PLAY WITH ANYONE / RANKED MATCH (the tree has no NpOnlineFriendsAvailable yet, so the shipping popup is the first one).
"""

NAME = "VitaKit24"          # the public name of the test account (MSC_ONLINE_NAME: 2-10 letters or digits). Made on the service by the first run that logs in; later runs sign in with its token

# 30 pictures a second in the menus: 1800 frames = 60 s. The queue wait is counted in frames (the route has no wall clock); online_check.py reads the real seconds from the
# `[np-net] req` times and the `[watch] rt=` lines and fails a run whose wait was under 45 s.
QUEUE_WAIT_FRAMES = 1800

BOOT = """# {title}
# Generated by tools/console-1.2/gen_online.py (edit the generator, not this file). One console, the real online service, no opponent: {what}
# Menus are driven by pad presses only; the public name comes from MSC_ONLINE_NAME in the run's np-player.txt (nothing is typed). Every screen logs a STATE line: a missing one is a TIMEOUT
# line of the script and the run is INVALID.
mash 100 20 scene == 0
log STATE title screen
mash 100 30 scene != 0
wait scene == 1 || scene == 10
wait scene == 10 || nbuttons >= 8
if scene == 10
log first run: no save file, accepting 'create save data'
wait nbuttons >= 2
idle 10
mash 100 30 scene == 1
wait nbuttons >= 8
endif
wait onctx == 0
log STATE main menu
idle 30
# The main menu is a ring picked by stick/D-pad angle; Multiplayer (ctx 1) is up-left.
hold 30 0 -80 80
wait onctx == 1 120
idle 10
log STATE pointer on multiplayer
idle 20
press 100
wait scene == 10 1200
log STATE multiplayer mode choice
wait nbuttons >= 3 900
idle 60
mash 8 15 onctx == 0 180
idle 10
press 100
log chose online
wait scene == 1 900
wait scene == 10 1200
wait nbuttons >= 3 900
log STATE online choice popup
idle 60
"""

# a popup button by its place in the choice popup (0 is the first)
def pick(n):
    return ("mash 4 15 onctx == %d 300\nidle 10\n" % n if n else "idle 10\n") + "press 100\n"


# Online Central after the login: the game's first-time notice (a popup) may come first. `target` is the scene to wait for (40 hub, 41 player count).
def login_to(target, label):
    return """wait scene == {t} || scene == 10 3600
if scene == 10
log STATE first-time notice
idle 120
mash 100 40 scene != 10 1200
endif
wait scene == {t} 3600
log STATE {label}
""".format(t=target, label=label)


# the pointer onto hub button n by whichever D-pad direction reaches it (each `try` ends at once when the pointer is already there), then Cross, then the scene it opens
def hub_button(n, scene, label, back):
    return """idle 60
try vmash down 12 onctx == {n} 150
try vmash right 12 onctx == {n} 150
try vmash up 12 onctx == {n} 150
try vmash left 12 onctx == {n} 150
vpress cross 3 60
wait scene == {s} 900
log STATE {label}
idle 300
log STATE {label} read, leaving
press 200
wait scene == 40 900
log STATE {back}
""".format(n=n, s=scene, label=label, back=back)


def search_and_cancel(label_search, wait_frames):
    return """idle 150
press 100
log chose one player
wait scene == 24 || scene == 49 2400
log STATE {l}
idle {w}
log STATE {l} waited
# a search that failed shows the game's own error popup over the search screen: it has one button and wants Cross (Circle does nothing there, and the route used
# to end stuck on it until its TIMEOUT). Cross closes it and the game leaves the online screens by itself; the route ends here with a clean exit and the run is
# INVALID by its missing STATE lines, with the reason in the log.
if scene == 10
log search FAILED: the game's error popup is up, closing it with Cross
press 100
idle 300
log STATE search failed (error popup closed)
exit
endif
press 200
idle 240
log STATE search cancelled
""".format(l=label_search, w=wait_frames)


END_TO_MENU = """# back out to the main menu: Circle leaves a scene one step at a time (player count -> hub -> main menu); a Circle that is not needed is not pressed
idle 60
if scene != 1
press 200
idle 180
endif
if scene != 1
press 200
idle 180
endif
if scene != 1
press 200
idle 180
endif
wait scene == 1 900
idle 60
log STATE back in the main menu
exit
"""


def route_hub():
    return BOOT.format(title="online hub: the online menu opens, the account is signed in (profile present), then back to the main menu",
                       what="MULTIPLAYER -> ONLINE -> RANKED MATCH opens Online Central (the login, the hub), dwell 10 s, Circle out") \
        + pick(2) + "log chose ranked\n" + login_to(40, "online hub") + "idle 300\nlog STATE hub read, leaving\n" + END_TO_MENU


def route_conn():
    return BOOT.format(title="connection check: HOST A ROOM fails (an address that cannot resolve), TEST CONNECTION runs, its result popup, back to the main menu",
                       what="the failure popup is the only way to the connection test and the isolated build's env reader refuses MSC_ONLINE_URL (no / or : in a value), so the console run needs a Wi-Fi with no internet (BY HAND); the host proof points the game at a loopback port nobody listens on") \
        + pick(0) + """log chose host
# the account step cannot reach the service: the failure popup with TEST CONNECTION as its second button
wait nbuttons >= 2 3600
log STATE failure popup with the test offered
idle 60
press 4
idle 20
press 100
log chose test connection
# the test's result popup (one OK)
idle 300
wait nbuttons >= 1 3600
log STATE result popup
idle 120
press 100
wait scene == 1 1800
idle 60
log STATE back in the main menu after the test
exit
"""


def route_quick():
    return BOOT.format(title="quick match: PLAY WITH ANYONE joins the matchmaking queue (the ranked pool today; the separate unranked pool is on agent/anypool24), 60 s wait with nobody to play, cancel, back to the main menu",
                       what="needs MSC_ONLINE_FRIENDS=1 (the tree does not offer FRIENDS / PLAY WITH ANYONE by itself yet); POST /v1/ranked/queue {}, polled until the cancel, DELETE on cancel") \
        + pick(1) + "log chose play with anyone\n" + login_to(41, "player count (quick)") + search_and_cancel("quick match searching", QUEUE_WAIT_FRAMES) + END_TO_MENU


def route_ranked():
    return BOOT.format(title="ranked queue: RANKED MATCH, the hub, RANKED MATCH again, 60 s wait with nobody to play, cancel, back to the main menu",
                       what="the ranked queue (POST /v1/ranked/queue {}), polled until the cancel, DELETE on cancel") \
        + pick(2) + "log chose ranked\n" + login_to(40, "online hub") + """idle 200
try vmash down 12 onctx == 1 150
try vmash right 12 onctx == 1 150
try vmash up 12 onctx == 1 150
try vmash left 12 onctx == 1 150
vpress cross 3 60
wait scene == 41 900
log STATE player count (ranked)
""" + search_and_cancel("ranked searching", QUEUE_WAIT_FRAMES) + END_TO_MENU


def route_lists():
    return BOOT.format(title="friends list and leaderboard: the hub's FRIENDS and RANKINGS screens, read only",
                       what="FRIENDS (GET /v1/friends, /v1/friends/status) and RANKINGS (POST /v1/rank/get) are looked at and left; nothing is written") \
        + pick(2) + "log chose ranked\n" + login_to(40, "online hub") + hub_button(3, 47, "friends list", "hub after the friends list") \
        + hub_button(2, 46, "rankings", "hub after the rankings") + END_TO_MENU


# ---- mp18 (w8/mp18.md, owner 23 Nov "make sure multiplayer works"; ONE Vita): the runs a single console can do alone ----
# The host's waits are counted in frames (30 a second in the menus): 1350 = 45 s, 1800 = 60 s.
HOST_WAIT_FRAMES = 1350
LAN_WAIT_FRAMES = 1800


def route_hostwait():
    """HOST A ROOM with nobody to invite: the account (preset name), the room on the service, STUN, the UDP bind chain (25110 first) and, with MSC_NET_RELAY_ONLY=1, the TURN
    allocation (`relay ready`): then 45 s in the game's status popup (stage 3, waiting for a partner), Circle cancels (`[online-menu] cancelled while connecting (stage 3)`)."""
    return BOOT.format(title="host a room alone: HOST A ROOM, the room is made on the service, 45 s in the waiting popup, cancel, back to the main menu",
                       what="POST /v1/rooms, the endpoint (STUN or, with MSC_NET_RELAY_ONLY=1, the TURN relay first), polled while nobody joins; Circle leaves the room (DELETE)") \
        + pick(0) + """log chose host
# the account step, the room and the transport: the game's status popup (its one button cancels). A failure popup would also have a button: the log's
# `[online-menu] failure:` line tells them apart (online_check.py).
wait nbuttons >= 1 3600
idle 300
log STATE room status popup
idle {w}
log STATE room waited
press 200
idle 240
log STATE room cancelled
""".format(w=HOST_WAIT_FRAMES) + END_TO_MENU.replace("idle 60\nlog STATE back in the main menu\nexit\n", "idle 150\nlog STATE back in the main menu\nexit\n")   # (5 s: the guard gives the core back 3 s after the screens close)


# BOOT up to the mode choice popup (MULTIPLAYER: ONLINE / LOCAL / CANCEL), for the local routes
BOOT_MODE = BOOT.split("mash 8 15 onctx == 0 180\n")[0]


def route_lanwait(which):
    """Local play, the host side alone: LOCAL -> SAME WI-FI (which=1: UDP 25100 on the access point) or NEARBY (which=0: the Vita's own ad hoc radio), Create Game, 60 s in the lobby
    with nobody to join, Circle out (the lobby, then multiplayer, end). The fourth core's online guard moves its threads off while the lobby is up and back 3 s after it closed."""
    label = "same wi-fi" if which == 1 else "nearby"
    return BOOT_MODE.replace("# {title}", "# local host alone (%s): Create Game, 60 s in the lobby with nobody to join, back to the main menu" % label.upper()) \
        .replace("{what}", "LOCAL -> %s, Create Game, wait, Circle out; nothing is sent to the online service" % label.upper()) + """mash 4 15 onctx == 1 180
idle 10
press 100
log chose local
wait scene == 1 900
wait scene == 10 1200
wait nbuttons >= 3 900
log STATE local choice popup
idle 60
""" + pick(which) + """log chose {label}
wait scene == 24 2400
log STATE lobby
idle 120
press 100
log created game
idle {w}
log STATE host waited alone
""".format(label=label, w=LAN_WAIT_FRAMES) + END_TO_MENU.replace("# back out to the main menu: Circle leaves a scene one step at a time (player count -> hub -> main menu)", "# back out to the main menu: Circle leaves the hosted game, then the lobby") \
        .replace("idle 60\nlog STATE back in the main menu\nexit\n", "idle 150\nlog STATE back in the main menu\nexit\n")


