#!/usr/bin/env python3
"""Write native/platform/vita/session/nav/st_<id>_<name>.txt: one route per real stadium (ids 0-15).

    python3 tools/gen_stadium_routes.py            # write
    python3 tools/gen_stadium_routes.py --check    # exit 1 when a file differs

Each route: boot to the main menu, launch a friendly match in that stadium (home 3 = Donkey Kong, away 6 = Waluigi, the match60 pair; CPU skill 3, 10 minutes),
walk-out, kick-off, then 4,000 frames of match60's stick moves in chunks of six, with each goal's celebration and replay played out (the CPU's Mega Strikes score most goals).
Log marks: @begin/@end st-walkout, st-play, st-goal-sequence (one pair per goal). --short writes 2,200 frames of play (stq_NN_*.txt) for the slow armhf harness.
"""
import argparse, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "console-1.2"))
import gen_routes as G   # noqa: E402

REPO = HERE.parent
OUT = REPO / "native/platform/vita/session/nav"
NAMES = ["battledome", "bowserstadium", "craterfield", "crystalcanyon", "dump", "galacticstadium", "kongacoliseum", "lavapit",
         "pipelinecentral", "stormship", "thepalace", "thunderisland", "underground", "vice", "wastelands", "sandtomb"]
CLOCK = 40
GOAL_TRY_UNUSED = ["if score0 == 0 && score1 == 0", "vchase 240 none ball", "vchase 150 none goal", "vhold 60 circle", "vpress circle 3 0", "idle 90", "endif"]


PLAY_FRAMES = 4000     # frames of stick moves (the CPU team, skill 3, scores now and then: its Mega Strikes are most of the goals, w6 console kit "replay")
CHUNK = 6              # stick moves between two looks at the game state


def route(i, short=False):
    boot, menus, holds = G.split_source(G.source_lines())
    frames = 2200 if short else PLAY_FRAMES
    out = ["# stadium route %d (%s): launch (skill 3, 10 min), walk-out, kick-off, %d frames of match60 stick moves with every goal's celebration and replay, exit" % (i, NAMES[i], frames),
           "# Generated by tools/gen_stadium_routes.py from match60.txt (the replay route's shape); edit the generator, not this file.",
           "# Same teams (home 3 = Donkey Kong, away 6 = Waluigi) and the same stick moves in every stadium, so only the stadium differs."]
    out += G.body_without_comment_header(boot)
    out += ["log STATE main menu", "idle 60",
            "launch mode=friendly stadium=%d home=3 away=6 hsk=0,1,2 ask=5,6,7 human=0 time=600 skill=3" % i,
            "wait ingame == 1 4000", "log @begin st-walkout", "try wait gs == 1 4000", "log @end st-walkout",
            "log STATE kick-off", "try wait gs == 5 1200", "log STATE open play", "log @begin st-play"]
    at = played = 0
    while played < frames:
        chunk = [holds[(at + k) % len(holds)] for k in range(CHUNK)]
        at += CHUNK
        played += sum(int(l.split()[1]) for l in chunk if l.startswith("hold "))
        out += ["if gs == 5"] + chunk + ["endif",
                "if gs == 2", "log @begin st-goal-sequence", "try wait gs == 1 3600", "log @end st-goal-sequence", "endif",
                "try wait gs == 5 || gs == 2 1200"]
    out += ["log @end st-play", "idle 60", "log stadium route done", "exit"]
    return "\n".join(out) + "\n"


WORST = {"st_worst_gpu.txt": (4, "st_worst_gpu: The Dump (stadium 4), the stadium the host census ranks worst for GPU (celebration 31.9 ms, open play 15.7 ms at 960x544 in the budget model: host ESTIMATES, nothing measured on a Vita).")}


def worst(i, title):
    t = route(i).splitlines()
    t[0] = "# " + title
    return "\n".join(t) + "\n"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true")
    ap.add_argument("--short", metavar="DIR", help="write the short variant (kick-off, a few seconds of play, then the goal run) as DIR/stq_NN_<name>.txt, for the slow armhf harness")
    a = ap.parse_args(); bad = 0
    if a.short:
        Path(a.short).mkdir(parents=True, exist_ok=True)
        for i, n in enumerate(NAMES): (Path(a.short) / ("stq_%02d_%s.txt" % (i, n))).write_text(route(i, True))
        return 0
    for i, n in enumerate(NAMES):
        p = OUT / ("st_%02d_%s.txt" % (i, n)); t = route(i)
        if a.check:
            if not p.exists() or p.read_text() != t: print("DIFFERS", p.name); bad = 1
        else:
            p.write_text(t)
    for fn, (i, title) in WORST.items():
        p = OUT / fn; t = worst(i, title)
        if a.check:
            if not p.exists() or p.read_text() != t: print("DIFFERS", p.name); bad = 1
        else: p.write_text(t)
    return bad


if __name__ == "__main__":
    sys.exit(main())
